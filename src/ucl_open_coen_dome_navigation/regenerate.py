import json
import subprocess
from pathlib import Path

import pydantic
from open_rigs.rigs import conditions

import ucl_open_coen_dome_navigation.task

SCHEMA_ROOT = Path("./src/DataSchemas/")
EXTENSIONS_ROOT = Path("./src/Extensions/")


def regenerate(model_type: type, schema_file: Path) -> None:
    """Write the JSON schema for one root model and run Bonsai.Sgen on it."""
    model = pydantic.RootModel[model_type]
    schema = model.model_json_schema(by_alias=True, mode="serialization", union_format="primitive_type_array")
    schema_file.write_text(json.dumps(schema, indent=2))
    subprocess.run(
        [
            "dotnet",
            "bonsai.sgen",
            str(schema_file),
            "--output",
            str(EXTENSIONS_ROOT),
            "--serializer",
            "json",
            "--serializer",
            "yaml",
        ],
        check=True,
    )


def task_schema_cs() -> str:
    """TaskSchema.Generated.cs: what the C# reads from the task schema rather than copying it."""
    task = ucl_open_coen_dome_navigation.task
    session = ", ".join(f'"{path}"' for path in task.SESSION_FIELDS)
    lists = ", ".join(f'"{path}"' for path in task.LIST_FIELDS)
    return (
        "// Generated by regenerate-schemas from the task schema; do not edit.\n"
        "public static class TaskSchema\n{\n"
        "    /// <summary>x-session-fields: what a condition may not set (the path or any path under it).</summary>\n"
        f"    public static readonly string[] SessionFields = {{ {session} }};\n"
        "    /// <summary>x-max-combinations: the most combinations one condition may expand into.</summary>\n"
        f"    public const int MaxCombinations = {conditions.MAX_COMBINATIONS};\n"
        "    /// <summary>The list fields one entry of which each trial draws (open_rigs.rigs.conditions.pick_lists), by path.</summary>\n"
        f"    public static readonly string[] ListFields = {{ {lists} }};\n"
        "}\n"
    )


def main():
    """Regenerate the task's JSON schema and Bonsai.Sgen C# classes from its pydantic model (the rig's are lib-open-rigs' OpenRigs.Devices.Rigs)."""
    SCHEMA_ROOT.mkdir(parents=True, exist_ok=True)
    (EXTENSIONS_ROOT / "TaskSchema.Generated.cs").write_text(task_schema_cs(), encoding="utf-8")
    regenerate(ucl_open_coen_dome_navigation.task.UclOpenCoenDomeNavigationTaskLogic, SCHEMA_ROOT / "ucl_open_coen_dome_navigation_task.json")


if __name__ == "__main__":
    main()
